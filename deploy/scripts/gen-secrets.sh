#!/usr/bin/env bash
# Writes deploy/secrets/store.yaml and deploy/secrets/platform.yaml with random values.
# Existing files are never overwritten (a regenerated password would lock the running
# WordPress / Postgres out), so delete a file deliberately if you want new values.
# deploy/secrets/ is git-ignored. Both files are passed to helm with -f by deploy.sh.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

need openssl OPENSSL
SECRETS_DIR="$ROOT/deploy/secrets"
mkdir -p "$SECRETS_DIR"

# hex = alphanumeric: safe inside URLs (DATABASE_URL), shell and WordPress application passwords.
rand_hex()    { openssl rand -hex "$1"; }
rand_base64() { openssl rand -base64 "$1" | tr -d '\n'; }

# The woo token must be identical in both files (store: secrets.mcpAuthToken, platform:
# secrets.wooMcpToken). Reuse the existing one when exactly one of the files already exists.
WOO_TOKEN=""
if [ -f "$SECRETS_DIR/store.yaml" ]; then
  WOO_TOKEN="$(sed -n 's/^ *mcpAuthToken: *"\{0,1\}\([^"]*\)"\{0,1\}.*$/\1/p' "$SECRETS_DIR/store.yaml" | head -n 1)"
elif [ -f "$SECRETS_DIR/platform.yaml" ]; then
  WOO_TOKEN="$(sed -n 's/^ *wooMcpToken: *"\{0,1\}\([^"]*\)"\{0,1\}.*$/\1/p' "$SECRETS_DIR/platform.yaml" | head -n 1)"
fi
[ -n "$WOO_TOKEN" ] || WOO_TOKEN="$(rand_hex 24)"

if [ -f "$SECRETS_DIR/store.yaml" ]; then
  log "deploy/secrets/store.yaml exists, keeping it"
else
  log "writing deploy/secrets/store.yaml"
  cat > "$SECRETS_DIR/store.yaml" <<EOF
# Generated by deploy/scripts/gen-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Git-ignored. Do not commit.
secrets:
  adminPassword: "$(rand_hex 12)"
  dbPassword: "$(rand_hex 16)"
  dbRootPassword: "$(rand_hex 16)"
  mcpAuthToken: "$WOO_TOKEN"
  wooAppPassword: "$(rand_hex 12)"
EOF
fi

if [ -f "$SECRETS_DIR/platform.yaml" ]; then
  log "deploy/secrets/platform.yaml exists, keeping it"
else
  log "writing deploy/secrets/platform.yaml"
  cat > "$SECRETS_DIR/platform.yaml" <<EOF
# Generated by deploy/scripts/gen-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Git-ignored. Do not commit.
secrets:
  adminEmail: admin@example.com
  adminPassword: "$(rand_hex 12)"
  demoMemberEmail: member@example.com
  demoMemberPassword: "$(rand_hex 12)"
  encryptionKey: "$(rand_base64 32)"
  sessionSecret: "$(rand_hex 32)"
  postgresPassword: "$(rand_hex 16)"
  anthropicApiKey: ""
  llmApiKey: ""
  wooMcpToken: "$WOO_TOKEN"
  notesMcpToken: "$(rand_hex 24)"
  utilsMcpToken: "$(rand_hex 24)"
EOF
fi

chmod 600 "$SECRETS_DIR"/*.yaml 2>/dev/null || true
log "secrets ready in deploy/secrets/ (store admin password: see store.yaml, dashboard admin: platform.yaml)"
